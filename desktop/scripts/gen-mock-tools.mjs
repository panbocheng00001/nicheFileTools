// Generates src/lib/mock-tools.generated.ts from src-tauri/tools.json.
//
// The desktop UI can run in two modes:
//   1. inside the Tauri window  -> tools come from the Rust `list_tools` command
//   2. in a plain browser       -> `npm run dev` (vite only), no IPC available
// For (2) we ship a snapshot of the manifest so the layout can be previewed.
// Regenerating from the real file keeps the two in sync; run `npm run sync:tools`.
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const manifestPath = resolve(root, "src-tauri", "tools.json");
const outPath = resolve(root, "src", "lib", "mock-tools.generated.ts");

const manifest = JSON.parse(readFileSync(manifestPath, "utf8"));
const tools = Array.isArray(manifest) ? manifest : manifest.tools ?? [];

if (tools.length === 0) {
  console.error("[sync:tools] tools.json contains no tools — aborting.");
  process.exit(1);
}

const entries = tools
  .map((t) => {
    const rec = {
      slug: t.slug,
      name: t.name,
      class: t.class ?? "A",
      engines: t.engines ?? [],
      source: t.source ?? [],
      target: t.target ?? "",
      output_kind: t.output_kind ?? "file",
      guide: t.guide ?? null,
      category: t.category ?? null,
      web_slug: t.web_slug ?? null,
    };
    return `  ${JSON.stringify(rec)},`;
  })
  .join("\n");

const file = `// AUTO-GENERATED by scripts/gen-mock-tools.mjs — do not edit by hand.
// Source of truth: src-tauri/tools.json. Regenerate with \`npm run sync:tools\`.
import type { ToolMeta } from "./tauri";

/// Snapshot of the desktop tool manifest. Only used when the UI runs in a plain
/// browser (no Tauri IPC) so the layout can be previewed; the native window
/// always reads the live manifest through \`list_tools\`.
export const MOCK_TOOLS: ToolMeta[] = [
${entries}
];
`;

mkdirSync(dirname(outPath), { recursive: true });
writeFileSync(outPath, file, "utf8");
console.log(`[sync:tools] ${tools.length} tools -> src/lib/mock-tools.generated.ts`);
